"""Generate native water math from the canonical GDScript scalar subset.

Run after editing water_math.gd; --check rejects a stale checked-in C# file.
Only constants, float parameters/locals, if/return and scalar expressions are
accepted. Unknown syntax fails rather than silently producing different code.
No Godot or Python dependency is added to the normal game build.
"""
import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "scripts/core/water_math.gd"
TARGET = ROOT / "scripts/core/WaterMath.cs"


def expression(value):
    value = re.sub(r"\babsf\(", "Math.Abs(", value)
    value = re.sub(r"\bmaxf\(", "Math.Max(", value)
    value = re.sub(r"\bINF\b", "double.PositiveInfinity", value)
    return value.replace(" or ", " || ").replace(" and ", " && ")


def generate():
    source = SOURCE.read_text(encoding="utf-8")
    digest = hashlib.sha256(source.replace("\r\n", "\n").encode("utf-8")).hexdigest()
    lines = ["// Generated by tools/generate_water_math.py; edit water_math.gd instead.",
             "using System;", "", "internal static class WaterMath", "{",
             f'\tpublic const string SourceHash = "{digest}";']
    function = False
    branch = False
    for number, raw in enumerate(source.splitlines(), 1):
        text = raw.strip()
        if not text or text.startswith("#") or text == "extends RefCounted":
            continue
        if branch and not raw.startswith("\t\t"):
            lines.append("\t\t}")
            branch = False
        if raw.startswith("static func "):
            if function:
                lines.append("\t}")
            match = re.fullmatch(r"static func (\w+)\((.*)\) -> float:", text)
            if not match:
                raise ValueError(f"Unsupported function at {number}: {raw}")
            name, params = match.groups()
            parameters = []
            for param in params.split(", "):
                parsed = re.fullmatch(r"(\w+): float", param)
                if not parsed:
                    raise ValueError(f"Unsupported parameter: {param}")
                parameters.append("double " + parsed[1])
            lines += ["", f"\tpublic static double {name}({', '.join(parameters)})", "\t{"]
            function = True
        elif match := re.fullmatch(r"const (\w+) := (.+)", text):
            if function:
                raise ValueError("Constants must precede functions")
            lines.append(f"\tpublic const double {match[1]} = {expression(match[2])};")
        elif raw.startswith("\t") and function:
            indent = "\t\t\t" if branch else "\t\t"
            if match := re.fullmatch(r"var (\w+) := (.+)", text):
                lines.append(f"{indent}double {match[1]} = {expression(match[2])};")
            elif text.startswith("if ") and text.endswith(":") and not branch:
                lines += [f"{indent}if ({expression(text[3:-1])})", indent + "{"]
                branch = True
            elif text.startswith("return "):
                lines.append(f"{indent}return {expression(text[7:])};")
            else:
                raise ValueError(f"Unsupported statement at {number}: {raw}")
        else:
            raise ValueError(f"Unsupported syntax at {number}: {raw}")
    if branch:
        lines.append("\t\t}")
    if function:
        lines.append("\t}")
    return "\n".join(lines + ["}", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != output:
            parser.exit(1, "WaterMath.cs is stale; run python tools/generate_water_math.py\n")
        print("WaterMath.cs matches the canonical GDScript")
    else:
        TARGET.write_text(output, encoding="utf-8", newline="\n")
        print(f"Generated {TARGET.relative_to(ROOT)}")
